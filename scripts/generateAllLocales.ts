// Function to build dictionary with specific language mappings
function buildLanguageLocale(lang: string, specificMap: Record<string, string>, fallbackMap: Record<string, string>): Record<string, string> {
  const result: Record<string, string> = {};
  for (const key of Object.keys(de)) {
    if (specificMap[key]) {
      result[key] = specificMap[key];
    } else if (fallbackMap[key]) {
      result[key] = fallbackMap[key];
    } else if ((en as any)[key]) {
      result[key] = (en as any)[key];
    } else {
      result[key] = (de as any)[key];
    }
  }
  return result;
}

